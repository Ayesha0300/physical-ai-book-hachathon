def check_for_hallucinations(response: str, context_chunks: List[Dict]) -> bool:
    """
    Check if the response contains hallucinations (information not in the context).
    
    Args:
        response: The response generated by the LLM
        context_chunks: List of context chunks that were provided to the LLM
        
    Returns:
        True if no hallucinations detected, False otherwise
    """
    return validate_response_against_context(response, context_chunks)

def validate_answer_only_mode(query: str, response: str, context_chunks: List[Dict]) -> bool:
    """
    Validate that the response adheres to 'answer only from selected text' mode.
    
    Args:
        query: The original query
        response: The response generated by the LLM
        context_chunks: List of context chunks that were provided to the LLM
        
    Returns:
        True if response adheres to 'answer only' mode, False otherwise
    """
    # Check if the response is grounded in the context
    is_context_valid = validate_response_against_context(response, context_chunks)
    
    # If the response is not grounded in context, check if it appropriately declines
    if not is_context_valid:
        decline_phrases = [
            "cannot answer based on the provided context",
            "i don't have enough information",
            "not mentioned in the context",
            "not found in the provided text"
        ]
        
        response_lower = response.lower()
        for phrase in decline_phrases:
            if phrase in response_lower:
                return True  # Appropriately declined to answer
        
        return False  # Not properly adhering to answer-only mode
    
    return True
