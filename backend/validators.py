from typing import List, Dict
import logging

def validate_response_against_context(response: str, context_chunks: List[Dict]) -> bool:
    """
    Validate that the response is grounded in the provided context.
    
    Args:
        response: The response generated by the LLM
        context_chunks: List of context chunks that were provided to the LLM
        
    Returns:
        True if response is grounded in context, False otherwise
    """
    # Extract context content
    context_content = " ".join([chunk.get('payload', {}).get('content', '') for chunk in context_chunks if 'payload' in chunk])
    
    # Simple heuristic: check if key information in response is present in context
    # This is a basic validation - in a real implementation, you might use more sophisticated NLP techniques
    response_words = set(response.lower().split())
    context_words = set(context_content.lower().split())
    
    # If less than 50% of the response words are in the context, consider it invalid
    if len(response_words) == 0:
        return True  # Empty response is valid
    
    common_words = response_words.intersection(context_words)
    if len(common_words) / len(response_words) < 0.5:
        logging.warning("Response may contain information not present in context")
        return False
    
    return True

